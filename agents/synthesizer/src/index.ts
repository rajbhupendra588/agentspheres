import { createAgent } from "@agentsphere/sdk";
import type { AgentCard } from "@agentsphere/contracts";

const port = Number(process.env.PORT ?? 9002);
const baseUrl = process.env.AS_AGENT_BASE_URL ?? `http://localhost:${port}`;

const card: AgentCard = {
  apiVersion: "agentsphere.io/v1",
  kind: "AgentCard",
  metadata: {
    name: "synthesizer",
    version: "1.0.0",
    owner: "platform",
    tenantId: process.env.AS_TENANT_ID ?? "default",
    projectId: process.env.AS_PROJECT_ID || undefined,
    labels: { team: "writing", mesh: "agentsphere" },
  },
  spec: {
    capabilities: ["synthesize.report", "summarize.short"],
    inputSchema: {
      type: "object",
      properties: {
        topic: { type: "string" },
        research: { type: "object" },
        text: { type: "string" },
      },
    },
    outputSchema: {
      type: "object",
      properties: {
        report: { type: "string" },
        summary: { type: "string" },
      },
    },
    endpoints: { invoke: "/v1/invoke" },
    resources: { timeoutMs: 30_000 },
    tools: [],
  },
};

const agent = createAgent({
  card,
  port,
  baseUrl,
  handler: async ({ input, capability }) => {
    const body = (input ?? {}) as {
      topic?: string;
      text?: string;
      research?: {
        findings?: Array<{ claim: string; confidence?: number }>;
        sources?: Array<{ title: string; url: string }>;
      };
    };

    if (capability === "summarize.short") {
      const text = body.text ?? body.topic ?? "";
      const summary =
        text.length <= 160 ? text : `${text.slice(0, 157).trimEnd()}...`;
      return { summary, chars: text.length };
    }

    const topic = body.topic ?? "Untitled";
    const findings = body.research?.findings ?? [];
    const sources = body.research?.sources ?? [];

    const bullets = findings
      .slice(0, 5)
      .map((f, i) => `${i + 1}. ${f.claim}`)
      .join("\n");

    const sourceLines = sources
      .slice(0, 5)
      .map((s, i) => `- [${i + 1}] ${s.title} (${s.url})`)
      .join("\n");

    const report = [
      `# ${topic}`,
      "",
      "## Executive summary",
      `Synthesized ${findings.length} findings across ${sources.length} sources via AgentSphere mesh.`,
      "",
      "## Key findings",
      bullets || "- No findings provided.",
      "",
      "## Sources",
      sourceLines || "- None",
      "",
      `_Generated by synthesizer@${card.metadata.version}_`,
    ].join("\n");

    return {
      topic,
      report,
      summary: `Report on "${topic}" with ${findings.length} findings.`,
      findingCount: findings.length,
      sourceCount: sources.length,
    };
  },
});

await agent.start();
console.log(`[synthesizer] ready at ${baseUrl} instance=${agent.instanceId}`);
